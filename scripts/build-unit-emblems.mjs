/**
 * Rebuild `src/shared/sekai/unit-emblems.data.ts` from `assets/unit-emblems/*.svg`.
 *
 * The SVGs are the source of truth: add or edit them, then run
 *
 *     bun scripts/build-unit-emblems.mjs
 *
 * The set may be partial — a unit with no SVG keeps using the hosted PNG — so
 * emblems can land one at a time. With the directory empty the generated table
 * is empty and nothing changes.
 *
 * Each file is stored whole (its own `viewBox` included) as an opaque string,
 * so a designer's export drops in unmodified: groups, gradients, `<style>`
 * blocks and multiple paths all survive. Two mechanical fixes are applied: the
 * XML prolog is dropped, and every `id` / class name is prefixed with the unit
 * key. That last one matters because editors emit the same `cls-1` in every
 * file, which would cross-style the others the moment more than one emblem is
 * inlined into a single document.
 *
 * The only hard requirements are a `viewBox` and no `<script>` / external
 * reference, since the markup is inlined into the page and into `data:` URLs.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const ROOT = resolve(import.meta.dirname, "..")
const SRC_DIR = join(ROOT, "assets/unit-emblems")
const OUT = join(ROOT, "src/shared/sekai/unit-emblems.data.ts")

/** Canonical order (`unitProfiles.seq`), so the generated file is stable. */
export const UNIT_ORDER = ["piapro", "light_sound", "idol", "street", "theme_park", "school_refusal"]

const SVG_NS = "http://www.w3.org/2000/svg"

/** Prefixes every `id`, `class` and `url(#…)` reference so files cannot collide. */
function scopeNames(markup, prefix) {
  const renamed = new Set()
  let scoped = markup.replace(/\b(id|class)="([^"]*)"/g, (_match, attr, value) => {
    const names = value.trim().split(/\s+/).filter(Boolean).map((name) => {
      renamed.add(name)
      return `${prefix}-${name}`
    })
    return `${attr}="${names.join(" ")}"`
  })
  // Selectors inside <style>, and url(#id) references, must follow the rename.
  for (const name of renamed) {
    const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    scoped = scoped
      .replace(new RegExp(`\\.${escaped}(?![\\w-])`, "g"), `.${prefix}-${name}`)
      .replace(new RegExp(`url\\(#${escaped}\\)`, "g"), `url(#${prefix}-${name})`)
  }
  return scoped
}

/** Validates one emblem file and returns the markup to inline. */
export function normalizeSvg(markup, name, prefix = name.replace(/\.svg$/, "")) {
  const withoutProlog = markup.replace(/^\s*<\?xml[^>]*\?>\s*/, "").trim()
  if (!/^<svg\b/.test(withoutProlog) || !withoutProlog.endsWith("</svg>")) {
    throw new Error(`${name}: expected a single <svg> root element`)
  }
  if (!/\bviewBox\s*=\s*"[^"]+"/.test(withoutProlog)) {
    throw new Error(`${name}: needs a viewBox, or it cannot scale to the icon sizes`)
  }
  if (/<script/i.test(withoutProlog)) {
    throw new Error(`${name}: <script> is not allowed — the markup is inlined into the page`)
  }
  if (/<(image|use)\b/i.test(withoutProlog) || /\bhref\s*=\s*"(?!#)/i.test(withoutProlog)) {
    throw new Error(`${name}: external references do not load from a data: URL`)
  }

  let scoped = scopeNames(withoutProlog, prefix)
  if (!scoped.includes("xmlns=")) {
    scoped = scoped.replace(/^<svg\b/, `<svg xmlns="${SVG_NS}"`)
  }
  return scoped.replace(/>\s+</g, "><")
}

export function main() {
  const files = readdirSync(SRC_DIR).filter((name) => name.endsWith(".svg"))
  const found = new Set(files.map((name) => name.replace(/\.svg$/, "")))
  const extra = [...found].filter((unit) => !UNIT_ORDER.includes(unit))
  if (extra.length > 0) {
    throw new Error(`unknown emblem SVGs (expected one of ${UNIT_ORDER.join(", ")}): ${extra.join(", ")}`)
  }

  const present = UNIT_ORDER.filter((unit) => found.has(unit))
  const entries = present.map((unit) => {
    const svg = normalizeSvg(readFileSync(join(SRC_DIR, `${unit}.svg`), "utf8"), `${unit}.svg`, unit)
    return `  ${unit}: ${JSON.stringify(svg)},`
  })

  writeFileSync(OUT, `// GENERATED by scripts/build-unit-emblems.mjs — do not edit by hand.
//
// Source of truth: assets/unit-emblems/*.svg. Drop emblem SVGs in there and
// re-run the script; a unit with no entry here keeps using the hosted PNG.

export const SEKAI_UNIT_EMBLEM_SVGS: Record<string, string> = {
${entries.length > 0 ? `${entries.join("\n")}\n` : ""}}
`, "utf8")

  const bytes = entries.reduce((total, line) => total + line.length, 0)
  const missing = UNIT_ORDER.filter((unit) => !found.has(unit))
  console.log(`wrote ${OUT.replace(`${ROOT}/`, "")} (${present.length} emblem(s), ${bytes} bytes)`)
  if (missing.length > 0) {
    console.log(`still on the hosted PNG: ${missing.join(", ")}`)
  }
}

if (import.meta.main) {
  main()
}
